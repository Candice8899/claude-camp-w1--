print("=== 个性化问候语生成器 ===")
name = input("请输入你的姓名：")
age = int(input("请输入你的年龄："))

if age < 18:
    stage = "你还年轻，未来充满可能！"
elif age < 60:
    stage = "你正值壮年，继续加油！"
else:
    stage = "岁月沉淀，您是最有智慧的人！"

print(f"""
-----------------------------
你好，{name}！
你今年 {age} 岁。
{stage}
祝你今天愉快！
-----------------------------
""")